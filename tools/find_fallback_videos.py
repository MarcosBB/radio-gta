"""Find a fallback video for every station that has only one (or replace a failed one).

Usage: python3 tools/find_fallback_videos.py              (stations without a fallback video)
       python3 tools/find_fallback_videos.py --station gta5-channel-x --replace
       python3 tools/find_fallback_videos.py --dry-run    (only write the report)

Searches YouTube with yt-dlp (no API quota), keeps "full station" videos of the same game whose
title names the station, checks with the YouTube Data API that they play embedded in Brazil,
prefers videos with a tracklist in the description and a length close to the primary video, and
adds the best one as the station's second video. Every candidate is listed in
fallback-report.md, so a choice can be swapped by hand. Run tools/build_tracks.py afterwards
to fetch the new tracklists.
"""
import argparse, json, re, subprocess, sys
from common import ROOT, env, hms, iso_secs, parse_tracklist, playable_problems, read_json, secs, write_json, youtube_videos

REPORT = ROOT / 'fallback-report.md'
MIN_LENGTH = 15 * 60

GAME_PATTERNS = {
    'gta6': [r'\bgta\s*(vi|6)\b', r'grand theft auto (vi|6)\b'],
    'gta5': [r'\bgta\s*(v|5)\b', r'grand theft auto (v|5)\b', r'\bgta online\b'],
    'gta4': [r'\bgta\s*(iv|4)\b', r'grand theft auto (iv|4)\b', r'\bthe ballad of gay tony\b', r'\bthe lost and damned\b'],
    'gtavcs': [r'vice city stories', r'\bvcs\b'],
    'gtalcs': [r'liberty city stories', r'\blcs\b'],
    'gtasa': [r'san andreas', r'\bgta\s*sa\b'],
    'gtavc': [r'vice city(?! stories)', r'\bgta\s*vc\b'],
    'gta3': [r'\bgta\s*(iii|3)\b', r'grand theft auto (iii|3)\b'],
}
EXCLUDE = {
    'gtavc': [r'stories', r'definitive'],
    'gta3': [r'stories', r'definitive'],
    'gtasa': [r'definitive'],
}
ALTERED = re.compile(r'remaster|anniversary|alternative radio|bass boost|\b8d\b|slowed|reverb|nightcore|sped up|reaction|\blyrics\b', re.I)
STOP_WORDS = {'the', 'fm', 'radio', 'los', 'santos', 'of'}


def words(s):
    return [w for w in re.sub(r'[^a-z0-9.]+', ' ', s.lower()).split() if w]


def key_words(station):
    return [w for w in words(station['name']) if w not in STOP_WORDS] or words(station['name'])


def name_match(station, title):
    t = ' '.join(words(title))
    key = key_words(station)
    return sum(1 for w in key if re.search(rf'\b{re.escape(w)}\b', t)) / len(key)


def game_match(game, title):
    t = title.lower()
    return any(re.search(p, t) for p in GAME_PATTERNS[game]) and not any(re.search(p, t) for p in EXCLUDE.get(game, []))


def search(query, n=12):
    out = subprocess.run(['yt-dlp', '--flat-playlist', '-J', '--no-warnings', f'ytsearch{n}:{query}'],
                         capture_output=True, text=True, timeout=120)
    if out.returncode:
        return []
    return [e for e in json.loads(out.stdout).get('entries', []) if e.get('id')]


def candidates(station, game):
    seen, found = set(station_ids(station)), []
    for query in [f"{game['full_name']} {station['name']} full radio", f"{game['label']} {station['name']} radio station"]:
        for e in search(query):
            if e['id'] in seen:
                continue
            seen.add(e['id'])
            title = e.get('title') or ''
            length, primary = e.get('duration') or 0, secs(station['videos'][0]['duration'])
            if length < MIN_LENGTH or not 0.5 <= length / primary <= 2 or ALTERED.search(title) or not game_match(station['game'], title):
                continue
            if name_match(station, title) < (1 if len(key_words(station)) <= 3 else 0.75):
                continue
            found.append({'id': e['id'], 'title': title, 'channel': e.get('channel') or e.get('uploader') or ''})
    return found


def station_ids(station):
    return [v['youtube_id'] for v in station['videos']]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--station', action='append', help='station id (repeatable); default: all without a fallback')
    ap.add_argument('--replace', action='store_true', help='replace the existing fallback video')
    ap.add_argument('--dry-run', action='store_true', help='do not change stations.json')
    args = ap.parse_args()
    key = env().get('YOUTUBE_API_KEY')
    if not key:
        sys.exit('YOUTUBE_API_KEY is missing in .env')

    stations = read_json('stations.json')
    games = {g['id']: g for g in read_json('games.json')}
    todo = [s for s in stations if (args.station and s['id'] in args.station) or (not args.station and len(s['videos']) < 2)]
    report = ['# Fallback video report', '', 'Generated by `tools/find_fallback_videos.py`. The chosen video is in bold.', '']
    missing = []
    for n, st in enumerate(todo, 1):
        cands = candidates(st, games[st['game']])
        items = youtube_videos([c['id'] for c in cands], key) if cands else {}
        primary = secs(st['videos'][0]['duration'])
        scored = []
        for c in cands:
            it = items.get(c['id'])
            if not it or playable_problems(it):
                continue
            length = iso_secs(it['contentDetails'].get('duration')) or 0
            tracks = len(parse_tracklist(it['snippet'].get('description', '')))
            score = 3 * name_match(st, c['title']) + (2 if tracks >= 5 else 0) + min(length, primary) / max(length, primary, 1)
            score += 0.5 if re.search(r'\bfull\b|complete', c['title'], re.I) else 0
            scored.append({**c, 'length': length, 'tracks': tracks, 'score': score})
        scored.sort(key=lambda c: -c['score'])
        print(f"[{n}/{len(todo)}] {st['game']} {st['name']}: {len(scored)} candidates" + (f" → {scored[0]['title']}" if scored else ''), flush=True)
        report += [f"## {st['game']} · {st['name']}", '']
        if not scored:
            report += ['No playable candidate found.', '']
            missing.append(st)
            continue
        for i, c in enumerate(scored[:5]):
            line = f"- [{c['title']}](https://youtu.be/{c['id']}) · {c['channel']} · {hms(c['length'])} · {c['tracks']} tracks"
            report.append(f'**{line[2:]}**' if i == 0 else line)
        report.append('')
        if not args.dry_run:
            best = {'youtube_id': scored[0]['id'], 'duration': hms(scored[0]['length'])}
            st['videos'] = st['videos'][:1] + [best] if args.replace or len(st['videos']) < 2 else st['videos']
        if n % 10 == 0 and not args.dry_run:
            write_json('stations.json', stations)
    if missing:
        report += ['## Stations without a fallback video', ''] + [f"- {s['game']} · {s['name']}" for s in missing]
    REPORT.write_text('\n'.join(report) + '\n')
    if not args.dry_run:
        write_json('stations.json', stations)
    print(f'{len(todo) - len(missing)}/{len(todo)} stations got a fallback video; see {REPORT.name}')


if __name__ == '__main__':
    main()
